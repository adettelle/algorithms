/*
-- ПРИНЦИП РАБОТЫ --
Считываем текст (строку без пробелов) и слова, которые формируют словарь.
Для ускорения поиска слов строим префиксное дерево (Trie). Каждая вершина Trie
хранит переходы по буквам a-z и признак finish, который показывает,
заканчивается ли в этой вершине слово из словаря.
Также используем динамическое программирование. Заводим массив dp длины len(text)+1,
где dp[i] означает, что первые i символов текста можно полностью разбить на слова
из словаря.
dp[0] считаем true, потому что пустую строку можно считать уже корректно разбитой.
Далее последовательно рассматриваем все позиции i текста.
Если dp[i] == true, то первые i символов уже можно разбить на допустимые слова.
Из этой позиции вызываем метод FindMatches структуры Trie, который ищет все слова
из словаря, начинающиеся в позиции i. Метод перемещается по тексту вперёд
и одновременно проходит соответствующий путь в Trie, начиная с корневой вершины.
Если соответствующего перехода в Trie нет, дальнейший поиск из этой позиции
прекращается.
Для каждой найденной вершины с finish == true метод FindMatches добавляет
в результат позицию окончания найденного слова. После завершения поиска
для всех найденных позиций end устанавливаем dp[end] = true.
В конце проверяем dp[len(text)]. Если оно равно true, значит, весь текст можно разбить
на слова из словаря.
Одно и то же слово можно использовать любое количество раз, поскольку из каждой
достижимой позиции мы снова начинаем поиск слов в Trie.

-- ДОКАЗАТЕЛЬСТВО КОРРЕКТНОСТИ --
Примем dp[0] = true, поскольку пустая строка не содержит символов и может считаться
разбитой на ноль слов.

Пусть dp[i] = true. Это означает, что первые i символов текста можно представить
как последовательность слов из словаря.

Алгоритм вызывает FindMatches из позиции i. Этот метод проходит по тексту вперёд
и одновременно перемещается по соответствующему пути в Trie. Если достигается
вершина с finish == true, значит, часть текста text[i:end] является словом
из словаря.
Так как первые i символов уже можно разбить на слова, добавление найденного слова
позволяет разбить первые end символов текста. Поэтому алгоритм устанавливает
dp[end] = true.
Таким образом, каждое значение dp[i], устанавливаемое алгоритмом,
действительно означает, что соответствующий префикс текста можно разбить
на слова из словаря.
Если в конце dp[len(text)] == true, это означает, что разбит весь текст.

-- ВРЕМЕННАЯ СЛОЖНОСТЬ --
Пусть N - длина строки (текста), M - количество слов в словаре,
L - максимальная длина слова в словаре.
Построение Trie требует времени O(M*L), так как каждый символ каждого слова
добавляется в Trie не более одного раза.
При обработке текста для каждой достижимой позиции i вызывается FindMatches.
Из одной позиции этот метод проходит вперёд не более чем на L символов,
поскольку длина любого слова в словаре не превышает L.
Таким образом, обработка текста занимает O(N*L) в худшем случае.
Итоговая временная сложность: O(M*L + N*L).

-- ПРОСТРАНСТВЕННАЯ СЛОЖНОСТЬ --
Пусть N - длина строки (текста), M - количество слов в словаре,
L - максимальная длина слова в словаре.
Массив dp содержит N + 1 элементов, поэтому занимает O(N) памяти.
Trie содержит не более M*L + 1 вершин, поскольку каждая новая вершина соответствует
одному символу, добавленному при построении Trie.
Для каждой вершины хранится массив из 26 переходов и признак finish,
поэтому память на Trie составляет O(M*L).
Метод FindMatches дополнительно создаёт массив найденных позиций. Из одной позиции
может быть найдено не более L слов, поэтому этот массив занимает O(L) памяти.
Итого общая пространственная сложность: O(N+M*L).
*/

