// Для Trie задача хранить словарь и уметь искать слова в тексте
type Trie struct {
	nodes []Node
}

type Node struct {
	next   [26]int
	finish bool
}

func NewNode() Node {
	node := Node{}
	// Пока ни одного перехода нет
	for i := range node.next {
		node.next[i] = -1
	}
	return node
}

// получает текст и позицию, а возвращает позиции, до которых
// заканчиваются слова словаря.
func (t *Trie) FindMatches(text string, start int) []int {
	res := make([]int, 0)

	v := 0

	// Берём слово по одной букве слева направо и добавляем его в Trie.
	// Если нужной ветки ещё нет - создаём её.
	// Если ветка уже есть - просто идём по ней
	for i := start; i < len(text); i++ {
		// Получаем индекс буквы text[j]
		index := text[i] - 'a'

		// смотрим, есть ли такой переход из trie.nodes[v]
		// Если переход есть - перейти в следующую вершину и проверить finish
		next := t.nodes[v].next[index]
		if next == -1 {
			break
		}
		// Теперь v указывает на вершину trie, в которую мы пришли по текущей букве
		v = next
		// если true, значит, слово из словаря закончилось именно здесь
		// а мы начали это слово с позиции i и сейчас находимся в позиции j.
		// Значит, текст от i до j включительно — допустимое слово.
		// j+1, потому что dp обозначает позицию после уже разобранного текста.
		if t.nodes[v].finish {
			res = append(res, i+1)
		}
	}
	// t.nodes[v].finish = true
	return res

}

// i - позиция символа в слове
// index - номер символа в алфавите от 0 до 25
// v - номер текущей вершины trie
// номера Node присваиваются в порядке добавления слов
func BuildTrie(dictionary []string) *Trie {
	// корень - trie.nodes[0]
	trie := &Trie{
		nodes: []Node{NewNode()},
	}

	for _, word := range dictionary {
		// v - текущая позиция в Trie
		v := 0

		// Берём слово по одной букве слева направо и добавляем его в Trie.
		// Если нужной ветки ещё нет - создаём её.
		// Если ветка уже есть - просто идём по ней
		for i := 0; i < len(word); i++ {
			// Берём текущую букву и превращаем её в номер от 0 до 25. 'a'= 97,
			// а всего букв в англ.алф. 26
			index := word[i] - 'a'

			// Смотрим, есть ли уже из текущ.вершины v переход по этой букве или нет?
			// -1 означает: «перехода по этой букве пока нет»
			if trie.nodes[v].next[index] == -1 {
				// Создаваемая сейчас новая вершина будет иметь номер len(trie.nodes).
				// запомним этот номер в переходе по текущей букве.
				trie.nodes[v].next[index] = len(trie.nodes)
				// Создаём эту новую вершину
				trie.nodes = append(trie.nodes, NewNode())
			}
			// Переходим в следующую вершину
			v = trie.nodes[v].next[index]
		}
		trie.nodes[v].finish = true
	}

	return trie
}

// v - номер текущей вершины trie
// буква текста -> переход в trie -> обновили v -> проверили finish -> обновили dp
// Это центральная часть всего алгоритма
// Для DP задача определять, какие позиции текста достижимы с помощью словаря
func IsCoveredByDictionary(text string, dictionary []string) bool {
	trie := BuildTrie(dictionary)

	dp := make([]bool, len(text)+1)
	dp[0] = true

	// Если dp[i] == true, начинаем из этой позиции идти по text вперёд
	for i := 0; i < len(text); i++ {
		// проверяем: можно ли вообще добраться до позиции i, разбивая
		// предыдущую часть текста на слова
		if !dp[i] {
			continue
		}

		// FindMatches нашёл слова и индексы их окончания, которые далее мы перебираем
		matches := trie.FindMatches(text, i)

		for _, end := range matches {
			dp[end] = true
		}
	}
	return dp[len(text)] // ==  dp[len(dp)-1]
}

// функция PrintTrie перебирает node.next от 0 до 25
// то есть она печатает буквы в алфавитном порядке
// а номера Node присваиваются в порядке добавления слов
func PrintTrie(trie *Trie) {
	for i, node := range trie.nodes {
		fmt.Printf("Node %d", i)
		if node.finish {
			fmt.Print(" (FINISH) ")
		}
		fmt.Println(":")

		for j, next := range node.next {
			if next != -1 {
				fmt.Printf(" %c -> Node %d\n", 'a'+j, next)
			}
		}
	}
}
