/*
-- ПРИНЦИП РАБОТЫ --
Считываем строки s и t.
Используем динамическое программирование.
dp[i][j] — минимальное количество операций, необходимое для преобразования
первых i символов строки s в первые j символов строки t.

Для вычисления очередной строки достаточно только предыдущей строки и текущей строки,
поскольку dp[i][j] зависит только от dp[i][j-1], dp[i-1][j] и dp[i-1][j-1].
Поэтому вместо всей матрицы храним два массива: prev — предыдущую строку и
cur — текущую. После вычисления очередной строки меняем их местами.

Аналогично матрице:
cur[j-1]  = dp[i][j-1]
prev[j]   = dp[i-1][j]
prev[j-1] = dp[i-1][j-1]

Первую строку заполняем числами 0, 1, 2, ... M, поскольку пустую строку
можно превратить в первые j символов строки t ровно за j вставок.
Первый столбец заполняем числами 0, 1, 2, ... N, поскольку первые i символов
строки s можно превратить в пустую строку ровно за i удалений.

Для остальных ячеек используем рекуррентную формулу:
dp[i][j] = min(dp[i][j-1] + 1, dp[i-1][j] + 1, dp[i-1][j-1] + x),
где x равен 0, если s[i-1] = t[j-1], и 1 иначе.

Три варианта соответствуют соответственно вставке символа, удалению символа
и замене последнего символа (либо отсутствию операции, если символы совпадают).

После заполнения всей матрицы искомое расстояние Левенштейна
находится в ячейке dp[N][M] или в prev[cols-1].

-- ДОКАЗАТЕЛЬСТВО КОРРЕКТНОСТИ --
Докажем, что dp[i][j] содержит минимальное количество операций
для преобразования первых i символов s в первые j символов t.

Для пустых строк: dp[0][j] = j, поскольку необходимо выполнить j вставок,
а dp[i][0] = i, поскольку необходимо выполнить i удалений.

Рассмотрим произвольные i > 0 и j > 0. Последняя операция преобразования
первых i символов s в первые j символов t может быть одной из трёх:
- Вставка последнего символа t. До неё первые i символов s уже были преобразованы
в первые j-1 символов t: dp[i][j-1] + 1.
- Удаление последнего символа s. До неё первые i-1 символов s уже были преобразованы
в первые j символов t: dp[i-1][j] + 1.
- Замена последнего символа s[i-1] на t[j-1]. До неё первые i-1 символов s
были преобразованы в первые j-1 символов t. Если символы равны,
дополнительная операция не нужна, иначе требуется одна замена: dp[i-1][j-1] + x.

Так как любая последовательность преобразований заканчивается одним из этих вариантов,
минимальное из трёх значений является оптимальным количеством операций.
Следовательно, dp[i][j] корректно вычисляется для каждой ячейки.

Таким образом, dp[N][M] содержит минимальное количество операций
для преобразования всей строки s в строку t, то есть искомое расстояние Левенштейна.

Для вычисления каждой строки используются только значения предыдущей и текущей строк.
Поэтому после вычисления строки более старые строки больше не нужны
и могут быть удалены из памяти.

-- ВРЕМЕННАЯ СЛОЖНОСТЬ --
Пусть N - длина строки s и M - длина строки t.
Матрица содержит (N+1)(M+1) ячеек. Каждая ячейка вычисляется за O(1) времени.

Следовательно, общая временная сложность алгоритма составляет: O(N*M).

-- ПРОСТРАНСТВЕННАЯ СЛОЖНОСТЬ --
Пространственная сложность оптимизированного алгоритма составляет O(M),
так как одновременно хранятся только две строки динамики длины M+1.
*/
package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	reader := bufio.NewReader(os.Stdin)
	var s, t string
	fmt.Fscan(reader, &s, &t)
	fmt.Println(Levenshtein(s, t))

}

// s x t = rows x cols
func Levenshtein(s, t string) int {
	rows := len(s) + 1
	cols := len(t) + 1

	// предыдущая строка динамики
	prev := make([]int, cols)
	cur := make([]int, cols)

	// dp[0][j] = j
	for j := 0; j < cols; j++ {
		prev[j] = j
	}

	for i := 1; i < rows; i++ {
		// dp[i][0] = i
		cur[0] = i

		for j := 1; j < cols; j++ {
			cost := 0
			if s[i-1] != t[j-1] {
				cost = 1
			}

			cur[j] = min(
				cur[j-1]+1,     // dp[i][j-1]+1,
				prev[j]+1,      // dp[i-1][j]+1,
				prev[j-1]+cost, // dp[i-1][j-1]+cost
			)
		}
		prev, cur = cur, prev
	}
	return prev[cols-1]
}

func LevenshteinMatrix(s, t string) int {
	rows := len(s) + 1
	cols := len(t) + 1

	dp := make([][]int, rows)

	for r := 0; r < rows; r++ {
		dp[r] = make([]int, cols)
	}
	for i := 0; i < cols; i++ {
		dp[0][i] = i
	}
	for i := 0; i < rows; i++ {
		dp[i][0] = i
	}
	// fmt.Println(dp)

	for i := 1; i < rows; i++ {
		for j := 1; j < cols; j++ {
			cost := 0
			if s[i-1] != t[j-1] {
				cost = 1
			}
			dp[i][j] = min(dp[i][j-1]+1, dp[i-1][j]+1, dp[i-1][j-1]+cost)
		}
	}
	// for r := 0; r < rows; r++ {
	// 	fmt.Println(dp[r])
	// }
	return dp[rows-1][cols-1]
}
